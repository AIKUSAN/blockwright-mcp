"""
Writes THIRD_PARTY_NOTICES.md: the licence text of every runtime dependency
that can end up in the bundled plugin (the dependency closure of package.json
"dependencies", minus the bun runtime). Run after `bun install`.

Copyright (c) 2026 AIKUSAN. Part of Blockwright MCP, distributed under GPL-3.0-only.
"""
import json, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
nm = root / "node_modules"
deps = [d for d in json.load(open(root / "package.json")).get("dependencies", {}) if d != "bun"]
seen, stack = {}, list(deps)
while stack:
    name = stack.pop()
    if name in seen: continue
    pj = nm / name / "package.json"
    if not pj.exists(): raise SystemExit(f"missing {name}: run bun install")
    data = json.load(open(pj)); seen[name] = data
    stack += list((data.get("dependencies") or {}).keys())
ADAPTED = """## Works adapted or bundled from other projects

These are not npm packages. Their licence texts are in `LICENSES/` and next to the files (`LICENSE.upstream`).

| Work | Source and commit | Licence | Where it is in this repository |
|---|---|---|---|
| Plugin code, tools and docs (the base of this project) | https://github.com/jasonjgardner/blockbench-mcp-plugin, `97a8a80` (v1.10.1), Jason J. Gardner and contributors | GPL-3.0-only | most of the repository; the whole work is GPL-3.0-only (`LICENSE`) |
| Tool catalogue and Blockbench-side command core (86 tools in sosadly 0.4.0, 76 registered here; `find_references` is not ported) | https://github.com/sosadly/blockbench-mcp, `b024728` (v0.4.0), Copyright (c) 2026 sosadly | MIT (`LICENSES/MIT-sosadly-blockbench-mcp.txt`) | `lib/sosadly/core.js` and `lib/sosadly/catalogue.ts` (generated by `build/port-sosadly.py`), `lib/orientation.ts`; each file carries the notice in its header |
| Behaviour tests for those tools | sosadly, `b024728`, `test/plugin-commands.test.js`, `plugin-generators.test.js`, `plugin-shapes.test.js` | MIT | `tests-node/sosadly/commands.test.mjs`, `generators.test.mjs`, `shapes.test.mjs` |
| Skill `blockbench-mcp-modeling` | sosadly, `b024728`, `skills/blockbench-mcp-modeling` | MIT | `skills/blockbench-mcp-modeling/`, unchanged; `UPSTREAM.md` and `LICENSE.upstream` beside it |
| 15 skills (`blockbench-use`, `blockbench-new-model`, `blockbench-mcp-overview`, `blockbench-modeling`, `blockbench-texturing`, `blockbench-pbr-materials`, `blockbench-animation`, `blockbench-particles`, `blockbench-hytale`, `blockbench-vanilla-textures`, `blockbench-gpt-image-textures`, `blockbench-flipbook-textures`, `blockbench-albedo-to-pbr`, `blockbench-substance`, `blockbench-development`) | https://github.com/jasonjgardner/blockbench-mcp-project, `e9c29a93e54bdd9aaa8a308196dfd4147e47d88c` | Apache-2.0 | `skills/<name>/`, unchanged; each has `UPSTREAM.md` and `LICENSE.upstream` |
| Agent `blockbench-physical-accuracy-reviewer` | blockbench-mcp-project, `e9c29a93e54bdd9aaa8a308196dfd4147e47d88c`, `agents/` | Apache-2.0 | `agents/`, unchanged; `UPSTREAM.md` and `LICENSE.upstream` beside it |
| Portions of `lib/geckolib-validate.ts` | https://github.com/adhi-jp/minecraft-blockbench-mcp, Copyright (c) 2026 adhi-jp | MIT | that file's header (already in the base) |

The skills and the agent are Markdown and small scripts. They are not part of `plugin/blockwright_mcp.js`.
Apache-2.0 sections 4(a) and 4(b): the licence text travels with the files, and they are not modified.
"""
out = ["# Third-party notices", "", ADAPTED,
       "## Packages bundled in the plugin", "",
       "The built plugin (`plugin/blockwright_mcp.js`) bundles code from these packages. Each is used under the licence reproduced below.", ""]
for name in sorted(seen):
    data = seen[name]
    files = sorted(p for p in (nm / name).iterdir() if p.is_file() and p.name.upper().startswith(("LICENSE", "LICENCE", "COPYING", "NOTICE")))
    out += [f"## {name} {data.get('version')} ({data.get('license')})", ""]
    if files:
        for f in files: out += ["```", f.read_text(errors="replace").strip(), "```", ""]
    elif (override := root / "build" / "licenses" / (name.replace("/", "__") + ".txt")).exists():
        # The package ships no licence file; this text is copied from its source repository.
        out += [f"The package ships no licence file. This text is from its source repository ({data.get('repository', {}).get('url', 'see package.json') if isinstance(data.get('repository'), dict) else data.get('repository')}):", "",
                "```", override.read_text().strip(), "```", ""]
    else:
        raise SystemExit(f"{name} ships no licence file; add its text to build/licenses/")
(root / "THIRD_PARTY_NOTICES.md").write_text("\n".join(out))
print(f"THIRD_PARTY_NOTICES.md: {len(seen)} packages")
