"""
Regenerates lib/sosadly/core.js and lib/sosadly/catalogue.ts from a checkout of
sosadly/blockbench-mcp (MIT). Usage: python3 build/port-sosadly.py <sosadly-checkout>

Copyright (c) 2026 AIKUSAN. Part of an unofficial fork of
jasonjgardner/blockbench-mcp-plugin, distributed under GPL-3.0-only.
"""
import pathlib, re, subprocess, sys

src = pathlib.Path(sys.argv[1])
out = pathlib.Path(__file__).resolve().parent.parent / "lib" / "sosadly"
commit = subprocess.check_output(["git", "-C", str(src), "rev-parse", "--short", "HEAD"]).decode().strip()
mit = (src / "LICENSE").read_text()
mit_block = "\n".join((" *     " + l).rstrip() for l in mit.strip().splitlines())

def header(kind, changes):
    return f"""/**
 * {kind} adapted from sosadly/blockbench-mcp, commit {commit}, used under the MIT License:
 *
{mit_block}
 *
 * Changes by AIKUSAN, 2026-11-06 (this file is distributed under GPL-3.0-only
 * as part of an unofficial fork of jasonjgardner/blockbench-mcp-plugin);
 * generated by build/port-sosadly.py:
{changes}
 */
"""

lines = (src / "plugin" / "blockbench_mcp.js").read_text().split("\n")
def find(pred, start=0):
    for i in range(start, len(lines)):
        if pred(lines[i]): return i
    raise SystemExit("marker not found")

i_iife = find(lambda l: l.strip() == "(function () {")
i_net0 = find(lambda l: l.startswith("let net = null;"))
i_net1 = find(lambda l: l.startswith("let deletables = [];"))
i_http = find(lambda l: l.startswith("function logActivity("))
i_max = find(lambda l: l.startswith("const MAX_BODY"))
i_ui = find(lambda l: l.startswith("let toggleAction = null;"))
i_buildui = find(lambda l: l.startswith("function buildUI() {"))

body = lines[i_iife + 1:i_net0] + lines[i_net1:i_http] + lines[i_http:i_max] + lines[i_ui:i_buildui]
text = "\n".join(body)

def sub(old, new, count=None, regex=False):
    global text
    n = len(re.findall(old, text)) if regex else text.count(old)
    if n == 0 or (count is not None and n != count):
        raise SystemExit(f"expected {count} of {old!r}, found {n}")
    text = re.sub(old, new, text) if regex else text.replace(old, new)

sub("globalThis.__BLOCKBENCH_MCP__", "globalThis.__BLOCKWRIGHT_SOSADLY__")
sub("const PLUGIN_ID = 'blockbench_mcp';", "const PLUGIN_ID = 'blockwright_sosadly';", 1)
sub("Preview.selected", "hooks.capturePreview()")
sub("new Promise((res) => Screencam.screenshotPreview(preview, opts, (d) => res(d)))", "Promise.resolve(hooks.shoot(preview, opts))", 1)
sub("await new Promise((resolve) => Screencam.screenshotPreview(preview, options, resolve))", "hooks.shoot(preview, options)", 1)
sub("require('fs')", "hooks.fs()")
# three.js lookAt keeps world up (+Y) as camera.up, so top/bottom views (nudged
# towards the front) put the model's right on the image LEFT. sosadly swapped up
# for the model's front there, which mislabelled those views (checked live,
# 2026-11-06: +X projects to NDC x -0.25 in its own top capture).
sub("if (Math.abs(vecDot(vecNorm(look), up)) > 0.95) up = o.front_vec;",
    "if (Math.abs(vecDot(vecNorm(look), up)) > 0.999999999) up = o.front_vec; // only exactly vertical is degenerate", 1)
# Keep the user's animation state: sosadly reset the timeline to 0 after sampling.
sub("""	const previous = Mode.selected ? Mode.selected.id : 'edit';
	const switched = previous !== 'animate';""", """	const previous = Mode.selected ? Mode.selected.id : 'edit';
	const switched = previous !== 'animate';
	const previousAnimation = typeof Animation !== 'undefined' ? Animation.selected : null;
	const previousTime = typeof Timeline !== 'undefined' ? Timeline.time : 0;""", 1)
sub("""		try { Timeline.setTime(0); } catch (e) {}
		try { Animator.showDefaultPose ? Animator.showDefaultPose() : Animator.preview(); } catch (e) {}
		if (switched && Modes.options[previous]) { try { Modes.options[previous].select(); } catch (e) {} }""", """		try { if (previousAnimation && Animation.selected !== previousAnimation) previousAnimation.select(); } catch (e) {}
		try { Timeline.setTime(previousTime); } catch (e) {}
		try {
			if (switched) { Animator.showDefaultPose ? Animator.showDefaultPose() : Animator.preview(); }
			else { Animator.preview(); }
		} catch (e) {}
		if (switched && Modes.options[previous]) { try { Modes.options[previous].select(); } catch (e) {} }""", 1)
sub("'blockbench_mcp_panel'", "'blockwright_copilot'", 2)
code_only = "\n".join(l for l in text.split("\n") if not l.lstrip().startswith(("//", "*", "/*")))
if "Screencam" in code_only or re.search(r"\brequire\(", code_only):
    raise SystemExit("unported Screencam or require left in core")

core = header("Blockbench-side command core", " * - the HTTP bridge, settings, menu actions and plugin registration are removed;\n"
    " * - every capture renders through hooks.capturePreview()/hooks.shoot(), a plugin-owned\n"
    " *   offscreen view, so the user's camera never moves;\n"
    " * - file access goes through hooks.fs(); global state and the panel id are renamed;\n"
    " * - withAnimationMode restores the selected animation and timeline time instead of resetting to 0;\n"
    " * - describeView keeps world up like three.js lookAt, fixing the top/bottom left-right labels.") + \
"""/* eslint-disable */
// @ts-nocheck
export function createSosadlyCore(hooks) {
""" + text + """

// Fork stubs for the removed bridge: the MCP server is the fork's own.
function startServer() { G.server = G.server || { fork: true }; G.port = hooks.port(); return { running: true }; }
function stopServer() { Blockbench.showQuickMessage('This panel is part of the Blockwright MCP plugin; disable the plugin to stop it.', 2500); return { running: true }; }
function getPort() { return hooks.port(); }
startServer();

return {
	commands,
	dispatch,
	buildPanel() { try { buildPanel(); } catch (e) { console.warn('[Blockwright MCP] could not build the Copilot panel:', e); } },
	teardown() {
		deletables.forEach((d) => { try { d.delete(); } catch (e) {} });
		deletables = [];
		mcpPanel = null;
		if (G.onActivity) G.onActivity = null;
	},
};
}
"""
(out / "core.js").write_text(core)

cat = (src / "src" / "tools.ts").read_text()
if cat.count('import { callBlockbench } from "./client.js";') != 1:
    raise SystemExit("catalogue import changed upstream")
cat = cat.replace('import { callBlockbench } from "./client.js";', 'import { callBlockbench } from "./client";')
(out / "catalogue.ts").write_text(header("Tool catalogue", " * - callBlockbench now dispatches in-process (lib/sosadly/client.ts) instead of over HTTP.") + "// @ts-nocheck\n" + cat)
print(f"core.js {len(core.splitlines())} lines, catalogue.ts {len(cat.splitlines())} lines, from {commit}")
